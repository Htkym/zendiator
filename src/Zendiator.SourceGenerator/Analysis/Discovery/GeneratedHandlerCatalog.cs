using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using static Zendiator.SourceGenerator.SymbolUtilities;

namespace Zendiator.SourceGenerator;

internal sealed record CatalogProducerResult(string Source,ImmutableArray<Diagnostic> Diagnostics);
internal static class GeneratedHandlerCatalog
{
    internal const string HeaderName="Zendiator.ZendiatorGeneratedCatalogAttribute";
    internal const string ExportName="Zendiator.ZendiatorHandlerExportAttribute";
    internal const string HintName="Zendiator.GeneratedCatalog.g.cs";
    internal static CatalogProducerResult Produce(Compilation compilation,ImmutableArray<MarkedHandlerDiscovery.Candidate> marked,CancellationToken ct)
    {
        if(marked.IsEmpty)return new("",ImmutableArray<Diagnostic>.Empty);
        var assembly=compilation.GetTypeByMetadataName(ContractNames.Handler)?.ContainingAssembly;
        var header=assembly?.GetTypeByMetadataName(HeaderName);var export=assembly?.GetTypeByMetadataName(ExportName);
        if(header==null||export==null)return new("",ImmutableArray<Diagnostic>.Empty);
        var existing=compilation.Assembly.GetAttributes().Where(a=>Same(a.AttributeClass,header)||Same(a.AttributeClass,export)).ToArray();
        if(existing.Length!=0)
        {
            var duplicates=existing.Where(a=>Same(a.AttributeClass,export)&&a.ConstructorArguments.Length>0&&a.ConstructorArguments[0].Value is INamedTypeSymbol)
                .GroupBy(a=>(INamedTypeSymbol)a.ConstructorArguments[0].Value!,SymbolEqualityComparer.Default).FirstOrDefault(g=>g.Count()>1);
            var bad=duplicates?.Skip(1).First()??existing[0];
            var location=bad.ApplicationSyntaxReference?.GetSyntax(ct).GetLocation()??Location.None;
            var original=duplicates?.First().ApplicationSyntaxReference?.GetSyntax(ct).GetLocation();
            return new("",ImmutableArray.Create(Diagnostic.Create(GeneratorDiagnostics.UnsupportedGenerationShape,location,
                original==null?Array.Empty<Location>():new[]{original},null,duplicates==null?
                    "Existing assembly catalog attributes conflict with generated catalog output. Remove them and regenerate the producer.":
                    "DuplicateCatalogExport: the same Handler definition is exported more than once.")));
        }
        var exports=new List<(INamedTypeSymbol Type,string Fingerprint)>();
        foreach(var candidate in marked.GroupBy(c=>c.Symbol,SymbolEqualityComparer.Default).Select(g=>g.First()))
        {
            ct.ThrowIfCancellationRequested();
            if(candidate.Model.CompilerOwnsMarkerError)continue;
            var fact=CatalogSignatureV1.Inspect(compilation,candidate.Symbol);
            // Local-only types remain usable locally; only valid public definitions are catalog exports.
            if(fact.Errors.Length==0)exports.Add((candidate.Symbol,CatalogSignatureV1.Fingerprint(fact)));
        }
        if(exports.Count==0)return new("",ImmutableArray<Diagnostic>.Empty);
        string Literal(string text)=>Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(text,true);
        var b=new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        b.Append("[assembly:global::Zendiator.ZendiatorGeneratedCatalogAttribute(1,0,").Append(Literal(compilation.Assembly.Identity.ToString()))
            .Append(',').Append(Literal(CatalogSignatureV1.Algorithm)).AppendLine(")]");
        foreach(var (type,fingerprint) in exports.OrderBy(x=>CatalogSignatureV1.TypeId(x.Type,false),StringComparer.Ordinal))
        {
            var declaration=HasParameters(type)?type.ConstructUnboundGenericType():type;
            b.Append("[assembly:global::Zendiator.ZendiatorHandlerExportAttribute(typeof(").Append(Name(declaration)).Append("),")
                .Append(Literal(fingerprint)).AppendLine(")]");
        }
        return new(b.ToString(),ImmutableArray<Diagnostic>.Empty);
    }
    internal static ImmutableArray<MarkedHandlerDiscovery.Candidate> Read(Compilation compilation,IAssemblySymbol assembly,
        CancellationToken ct,Action<string> reject)
    {
        var empty=ImmutableArray<MarkedHandlerDiscovery.Candidate>.Empty;
        if(Same(assembly,compilation.Assembly)){reject("UseLocalHandlers selects the current source assembly; UseCatalogFrom requires a referenced producer.");return empty;}
        var contracts=compilation.GetTypeByMetadataName(ContractNames.Handler)?.ContainingAssembly;
        var headerType=contracts?.GetTypeByMetadataName(HeaderName);var exportType=contracts?.GetTypeByMetadataName(ExportName);
        var attributes=assembly.GetAttributes();var headers=attributes.Where(a=>Same(a.AttributeClass,headerType)).ToArray();
        if(headers.Length!=1){reject(headers.Length==0?"MissingCatalog":"DuplicateCatalogHeader");return empty;}
        var header=headers[0];var args=header.ConstructorArguments;
        if(args.Length!=4||args.Any(v=>v.IsNull)||args[0].Value is not int major||args[1].Value is not int minor||
            args[2].Value is not string producer||args[3].Value is not string algorithm||minor<0)
        {reject("MalformedCatalog");return empty;}
        if(major!=1){reject("UnknownCatalogMajor: regenerate a compatible producer or use AddHandler for a known type.");return empty;}
        if(producer!=assembly.Identity.ToString()){reject("CatalogProducerMismatch");return empty;}
        if(algorithm!=CatalogSignatureV1.Algorithm){reject("UnknownFingerprintAlgorithm");return empty;}
        var required=header.NamedArguments.FirstOrDefault(a=>a.Key=="RequiredFeatures");
        if(required.Key!=null&&(required.Value.IsNull||required.Value.Kind!=TypedConstantKind.Array)){reject("MalformedCatalog");return empty;}
        if(required.Key!=null&&!required.Value.Values.IsDefaultOrEmpty){reject("UnknownRequiredCatalogFeature");return empty;}
        var selected=ImmutableArray.CreateBuilder<MarkedHandlerDiscovery.Candidate>();var seen=new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach(var attr in attributes.Where(a=>Same(a.AttributeClass,exportType)))
        {
            ct.ThrowIfCancellationRequested();var values=attr.ConstructorArguments;
            if(values.Length!=2||values[0].Value is not INamedTypeSymbol type){reject("MalformedCatalogExport");continue;}
            if(type.IsUnboundGenericType)type=type.OriginalDefinition;
            if(!Same(type.ContainingAssembly,assembly)){reject("CatalogForeignType: "+Name(type));continue;}
            if(!seen.Add(type)){reject("DuplicateCatalogExport: "+Name(type));continue;}
            var fact=CatalogSignatureV1.Inspect(compilation,type);
            foreach(var error in fact.Errors)reject(error+": "+Name(type));
            if(fact.Errors.Contains("UnsupportedCatalogSignature"))continue;
            if(values[1].Value is not string fingerprint||fingerprint.Length!=64||fingerprint.Any(c=>!Uri.IsHexDigit(c)))
            {reject("MalformedFingerprint: "+Name(type));continue;}
            if(fingerprint!=CatalogSignatureV1.Fingerprint(fact)){reject("StaleCatalogContract: "+Name(type));continue;}
            if(fact.Errors.Length!=0)continue;
            var candidate=MarkedHandlerDiscovery.BindExplicitMetadata(compilation,type,ct);
            if(candidate==null)reject("InvalidCatalogHandler: "+Name(type));
            else selected.Add(candidate);
        }
        return selected.ToImmutable();
    }
}
