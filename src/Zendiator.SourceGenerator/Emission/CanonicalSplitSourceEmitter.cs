using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Zendiator.SourceGenerator;

internal sealed record CanonicalSourceFile(string HintName, string Source)
{
    public CanonicalMediatorApi? Api { get; init; }
    public CanonicalCompositionFragment? Composition { get; init; }
    public EquatableArray<string> StreamHelpers { get; init; }
    public EquatableArray<string> BoxedDependencies { get; init; }
}
internal sealed record CanonicalCompositionFragment(string Namespace, string Registrar, EquatableArray<string> Externs,
    EquatableArray<CanonicalServiceDependency> Dependencies);
internal sealed record CanonicalRouteFile(CanonicalRouteText Route, CanonicalSourceFile File);
internal sealed record CanonicalOutputSelection(string Namespace, string RequestName, BoundDispatchFamily? Family);

// Route text owns execution; composition text owns provider construction and DI registration.
// IDs contain type/dispatch identity, never position or an enumeration ordinal.
internal static class CanonicalSplitSourceEmitter
{
    internal static string Id(string key)
    { using var hash = SHA256.Create(); return string.Concat(hash.ComputeHash(Encoding.UTF8.GetBytes(key)).Select(b => b.ToString("X2", CultureInfo.InvariantCulture))); }
    internal static StringBuilder Header(IEnumerable<string> declarations)
    {
        var b = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        foreach (var declaration in declarations.Distinct(StringComparer.Ordinal)) b.AppendLine(declaration);
        return b;
    }

    internal static void Mediator(StringBuilder b, IEnumerable<CanonicalServiceDependency> dependencies,
        IEnumerable<MemberDeclarationSyntax>? methods = null)
    {
        b.AppendLine("public sealed partial class Zendiator : IZendiator, global::System.IServiceProvider {");
        b.AppendLine(CanonicalRouteServiceEmitter.Services(dependencies));
        if (methods != null) foreach (var method in methods) b.AppendLine(method.NormalizeWhitespace().ToFullString());
        b.AppendLine("}");
    }

    internal static CanonicalSourceFile File(string hint, string source, CompilationUnitSyntax root, NamespaceDeclarationSyntax ns,
        ClassDeclarationSyntax mediator, CanonicalCompositionFragment fragment) => new(hint, source)
        {
            Api = new(ns.Name.ToString(), new(ns.Members.OfType<InterfaceDeclarationSyntax>().Single().Members.OfType<MethodDeclarationSyntax>()
                .Select(method => method.NormalizeWhitespace().ToFullString())), fragment.Externs),
            Composition = fragment,
            StreamHelpers = new(mediator.Members.OfType<MethodDeclarationSyntax>().Where(method => method.Modifiers.Any(SyntaxKind.PublicKeyword))
                .SelectMany(method => method.DescendantNodes().OfType<InvocationExpressionSyntax>())
                .Where(call => call.Expression is MemberAccessExpressionSyntax { Expression: SimpleNameSyntax, Name.Identifier.ValueText: "Create" or "CreateSource" } &&
                    call.ArgumentList.Arguments.FirstOrDefault()?.Expression is IdentifierNameSyntax { Identifier.ValueText: "_provider" })
                .Select(call => ((SimpleNameSyntax)((MemberAccessExpressionSyntax)call.Expression).Expression).Identifier.ValueText).Distinct(StringComparer.Ordinal))
        };
    internal static CanonicalSourceFile Route(CanonicalRouteText route)
    {
        if (route.Source.Length == 0) return new("", "");
        var root = CSharpSyntaxTree.ParseText(route.Source).GetCompilationUnitRoot(); var ns = root.Members.OfType<NamespaceDeclarationSyntax>().Single();
        var api = ns.Members.OfType<InterfaceDeclarationSyntax>().Single(); var mediator = ns.Members.OfType<ClassDeclarationSyntax>().Single(c => c.Identifier.ValueText == "Zendiator");
        var registrar = ns.Members.OfType<ClassDeclarationSyntax>().Single(c => c.Identifier.ValueText == "ZendiatorGeneratedRegistrar");
        var id = Id(route.StableKey);
        var fragment = CanonicalRouteServiceEmitter.Fragment(root, ns, mediator, registrar, route.BoxedDependencies);
        var b = Header(fragment.Externs);
        b.Append("namespace ").Append(fragment.Namespace).AppendLine(" {\npublic partial interface IZendiator {");
        foreach (var member in api.Members) b.AppendLine(member.ToFullString());
        b.AppendLine("}\npublic sealed partial class Zendiator : IZendiator {");
        foreach (var member in CanonicalRouteServiceEmitter.Route(ns, mediator)) b.AppendLine(member.NormalizeWhitespace().ToFullString());
        b.AppendLine("}\n}");
        return File("Zendiator.Route." + id + ".g.cs", b.ToString(), root, ns, mediator, fragment);
    }
    internal static EquatableArray<CanonicalOutputSelection> Accepted(CanonicalSyncEmissionModel sync, CanonicalAsyncEmissionModel async,
        CanonicalWrapperEmissionModel wrappers, CanonicalCapabilityEmissionModel capabilities, CanonicalMultiEmissionModel multi) => new(
        sync.Compositions.Select(c => new CanonicalOutputSelection(c.Namespace, c.Handler.RequestName, BoundDispatchFamily.SendSync))
        .Concat(async.Compositions.Select(c => new CanonicalOutputSelection(c.Namespace, c.Handler.RequestName, BoundDispatchFamily.SendAsync)))
        .Concat(wrappers.Compositions.Select(c => new CanonicalOutputSelection(c.Registration.Namespace, c.Registration.Handler.RequestName, c.Family)))
        .Concat(capabilities.Compositions.Select(c => new CanonicalOutputSelection(c.Registration.Namespace, c.Registration.Handler.RequestName, c.Family)))
        .Concat(multi.Compositions.SelectMany(c => c.Routes.Select(r => new CanonicalOutputSelection(c.Namespace, r.Registration.Handler.RequestName,
            r.Family)))));
    internal static CanonicalSourceFile? SelectRoute(CanonicalRouteText route, CanonicalSourceFile file, EquatableArray<CanonicalOutputSelection> selected) =>
        file.Source.Length != 0 && selected.Any(s => s.Namespace == route.Namespace && s.RequestName == route.RequestName && s.Family == route.Family) ? file : null;

    internal static IEnumerable<CanonicalSourceFile> Composition(IEnumerable<string> namespaces, IEnumerable<CanonicalCompositionFragment> fragments)
    {
        var selected = namespaces.ToArray();
        if (selected.Length == 0) yield break;
        var values = fragments.ToArray();
        foreach (var ns in selected)
        {
            var fragment = values.Single(value => value.Namespace == ns);
            yield return Composition(fragment);
        }
    }

    internal static IEnumerable<CanonicalSourceFile> Composition(CanonicalMultiEmissionModel model, IEnumerable<CanonicalCompositionFragment> fragments)
    {
        var values = fragments.ToArray();
        foreach (var composition in model.Compositions)
        {
            var routes = values.Where(value => value.Namespace == composition.Namespace).ToArray();
            if (routes.Length != composition.Routes.Count) throw new InvalidOperationException("Canonical composition route fragments mismatch.");
            var registrar = new StringBuilder();
            CanonicalRegistrationSourceEmitter.Emit(registrar, CanonicalRegistrationPlan.Multi(composition));
            var dependencies = routes.SelectMany(route => route.Dependencies).GroupBy(type => type.TypeName, StringComparer.Ordinal)
                .Select(group => group.First() with { Boxed = group.Any(type => type.Boxed) });
            yield return Composition(new(composition.Namespace, registrar.ToString(), new(CanonicalSymbolName.Declarations(composition.Routes[0].Registration.ExternAliases)
                .Split(new[] { '\n' }, StringSplitOptions.RemoveEmptyEntries)), new(dependencies)));
        }
    }

    private static CanonicalSourceFile Composition(CanonicalCompositionFragment fragment)
    {
        var b = Header(fragment.Externs);
        b.Append("namespace ").Append(fragment.Namespace).AppendLine(" {");
        Mediator(b, fragment.Dependencies);
        b.AppendLine(fragment.Registrar).AppendLine("}");
        return new("Zendiator.Composition." + Id(fragment.Namespace) + ".g.cs", b.ToString());
    }
}
