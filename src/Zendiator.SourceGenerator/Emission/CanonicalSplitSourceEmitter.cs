using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Zendiator.SourceGenerator;

internal sealed record CanonicalSourceFile(string HintName, string Source);
internal sealed record CanonicalRouteFile(CanonicalRouteText Route, CanonicalSourceFile File);
internal sealed record CanonicalOutputSelection(string Namespace, string RequestName, BoundDispatchFamily? Family);

// Route text owns execution; composition text owns provider construction and DI registration.
// IDs contain type/dispatch identity, never position or an enumeration ordinal.
internal static class CanonicalSplitSourceEmitter
{
    internal static string Id(string key)
    { using var hash = SHA256.Create(); return string.Concat(hash.ComputeHash(Encoding.UTF8.GetBytes(key)).Select(b => b.ToString("X2", CultureInfo.InvariantCulture))); }
    private static string Header(CompilationUnitSyntax root) => "// <auto-generated/>\n#nullable enable\n" + string.Concat(root.Externs.Select(e => e.WithLeadingTrivia().WithTrailingTrivia().ToString() + "\n"));
    private static string File(string header, NamespaceDeclarationSyntax ns, IEnumerable<MemberDeclarationSyntax> members) =>
        header + ns.WithLeadingTrivia().WithTrailingTrivia().WithMembers(SyntaxFactory.List(members)).NormalizeWhitespace().ToFullString() + "\n";
    internal static CanonicalSourceFile Route(CanonicalRouteText route)
    {
        if (route.Source.Length == 0) return new("", "");
        var root = CSharpSyntaxTree.ParseText(route.Source).GetCompilationUnitRoot(); var ns = root.Members.OfType<NamespaceDeclarationSyntax>().Single();
        var api = ns.Members.OfType<InterfaceDeclarationSyntax>().Single(); var mediator = ns.Members.OfType<ClassDeclarationSyntax>().Single(c => c.Identifier.ValueText == "Zendiator");
        var id = Id(route.StableKey);
        var methods = CanonicalRouteServiceEmitter.Route(ns, mediator);
        var partial = SyntaxFactory.Token(SyntaxKind.PartialKeyword);
        return new("Zendiator.Route." + id + ".g.cs", File(Header(root), ns, new MemberDeclarationSyntax[]{
            api.WithModifiers(api.Modifiers.Add(partial)),mediator.WithModifiers(mediator.Modifiers.Add(partial)).WithMembers(SyntaxFactory.List(methods))}));
    }
    internal static EquatableArray<CanonicalOutputSelection> Accepted(CanonicalSyncEmissionModel sync, CanonicalAsyncEmissionModel async,
        CanonicalWrapperEmissionModel wrappers, CanonicalCapabilityEmissionModel capabilities, CanonicalMultiEmissionModel multi) => new(
        sync.Compositions.Select(c => new CanonicalOutputSelection(c.Namespace, c.Handler.RequestName, BoundDispatchFamily.SendSync))
        .Concat(async.Compositions.Select(c => new CanonicalOutputSelection(c.Namespace, c.Handler.RequestName, BoundDispatchFamily.SendAsync)))
        .Concat(wrappers.Compositions.Select(c => new CanonicalOutputSelection(c.Registration.Namespace, c.Registration.Handler.RequestName, c.Family)))
        .Concat(capabilities.Compositions.Select(c => new CanonicalOutputSelection(c.Registration.Namespace, c.Registration.Handler.RequestName, c.Family)))
        .Concat(multi.Compositions.SelectMany(c => c.Routes.Select(r => new CanonicalOutputSelection(c.Namespace, r.Registration.Handler.RequestName,
            r.Family)))));
    internal static CanonicalSourceFile? SelectRoute(CanonicalRouteText route, CanonicalSourceFile file, EquatableArray<CanonicalOutputSelection> selected) =>
        file.Source.Length != 0 && selected.Any(s => s.Namespace == route.Namespace && s.RequestName == route.RequestName && s.Family == route.Family) ? file : null;

    internal static IEnumerable<CanonicalSourceFile> Composition(string source)
    {
        if (source.Length == 0) yield break;
        var root = CSharpSyntaxTree.ParseText(source).GetCompilationUnitRoot();
        foreach (var ns in root.Members.OfType<NamespaceDeclarationSyntax>())
        {
            var mediator = ns.Members.OfType<ClassDeclarationSyntax>().Single(c => c.Identifier.ValueText == "Zendiator");
            var registrar = ns.Members.OfType<ClassDeclarationSyntax>().Single(c => c.Identifier.ValueText == "ZendiatorGeneratedRegistrar");
            var generated = CanonicalRouteServiceEmitter.Composition(ns, mediator, registrar);
            yield return new("Zendiator.Composition." + Id(ns.Name.ToString()) + ".g.cs", File(Header(root), ns, new MemberDeclarationSyntax[] { generated.Shared, generated.Registrar }));
        }
    }
}
