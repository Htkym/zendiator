using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
namespace Zendiator.SourceGenerator;

// Reuses backend-generated members; it does not rewrite callbacks or introduce a runtime router.
internal static class CanonicalMultiSourceEmitter
{
    internal static string RouteSource(CanonicalMultiRouteEmission r) => r.Sync != null ? CanonicalSyncSourceEmitter.Emit(new(new(new[] { r.Sync }))) :
        r.Async != null ? CanonicalAsyncSourceEmitter.Emit(new(new(new[] { r.Async }))) :
        r.Wrapper != null ? CanonicalWrapperSourceEmitter.Emit(new(new(new[] { r.Wrapper }))) :
        CanonicalCapabilitySourceEmitter.Emit(new(new(new[] { r.Capability! })));
    private static string Suffix(string key)
    { using var hash = SHA256.Create(); return "__" + string.Concat(hash.ComputeHash(Encoding.UTF8.GetBytes(key)).Select(b => b.ToString("X2", CultureInfo.InvariantCulture))); }
    internal static string Emit(CanonicalMultiEmissionModel model) => Emit(model, RouteSource);
    internal static string Emit(CanonicalMultiEmissionModel model, Func<CanonicalMultiRouteEmission, string> source)
    {
        if (model.Compositions.Count == 0) return "";
        var text = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        text.Append(CanonicalSymbolName.Declarations(model.Compositions.SelectMany(c => c.Routes).SelectMany(r => r.Registration.ExternAliases)));
        foreach (var composition in model.Compositions)
        {
            var interfaces = new List<MemberDeclarationSyntax>(); var methods = new List<MemberDeclarationSyntax>();
            var handlerCalls = new List<(int Ordinal, StatementSyntax Call)>(); var pipelineCalls = new List<(int Ordinal, StatementSyntax Call)>();
            var dependencies = new List<StatementSyntax>(); var seen = new HashSet<string>(StringComparer.Ordinal); BlockSyntax? registrar = null; var first = true;
            foreach (var route in composition.Routes)
            {
                var root = CSharpSyntaxTree.ParseText(source(route)).GetCompilationUnitRoot();
                var ns = root.Members.OfType<NamespaceDeclarationSyntax>().Single();
                var api = ns.Members.OfType<InterfaceDeclarationSyntax>().Single(); interfaces.AddRange(api.Members);
                var mediator = ns.Members.OfType<ClassDeclarationSyntax>().Single(c => c.Identifier.ValueText == "Zendiator");
                var rewriter = new RouteNames(mediator, Suffix(route.Key));
                foreach (var member in mediator.Members)
                {
                    if (member is FieldDeclarationSyntax or ConstructorDeclarationSyntax) { if (first) methods.Add(member); }
                    else methods.Add((MemberDeclarationSyntax)rewriter.Visit(member)!);
                }
                var add = ns.Members.OfType<ClassDeclarationSyntax>().Single(c => c.Identifier.ValueText == "ZendiatorGeneratedRegistrar").Members.OfType<MethodDeclarationSyntax>().Single();
                registrar ??= add.Body!;
                foreach (var statement in add.Body!.Statements)
                {
                    if (statement is ExpressionStatementSyntax { Expression: InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax access } } && access.Expression is IdentifierNameSyntax { Identifier.ValueText: "expected" })
                    {
                        if (access.Name.Identifier.ValueText == "Handlers") handlerCalls.Add((route.HandlerOrdinal, statement));
                        if (access.Name.Identifier.ValueText == "Pipeline") pipelineCalls.Add((route.PipelineOrdinal, statement));
                    }
                    else if (statement is ExpressionStatementSyntax { Expression: InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax method } } && method.Name.Identifier.ValueText == "TryAdd")
                    { if (seen.Add(statement.ToString())) dependencies.Add(statement); }
                }
                first = false;
            }
            var statements = new List<StatementSyntax>(); var inserted = false;
            foreach (var statement in registrar!.Statements)
            {
                if (statement is ExpressionStatementSyntax { Expression: InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax access } } && access.Expression is IdentifierNameSyntax { Identifier.ValueText: "expected" } && access.Name.Identifier.ValueText is "Handlers" or "Pipeline")
                {
                    if (!inserted) { statements.AddRange(handlerCalls.OrderBy(x => x.Ordinal).Select(x => x.Call)); statements.AddRange(pipelineCalls.OrderBy(x => x.Ordinal).Select(x => x.Call)); inserted = true; }
                    continue;
                }
                if (statement is ExpressionStatementSyntax { Expression: InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax method } } && method.Name.Identifier.ValueText == "TryAdd") continue;
                if (statement is ReturnStatementSyntax) statements.AddRange(dependencies);
                statements.Add(statement);
            }
            text.Append("namespace ").Append(composition.Namespace).AppendLine("{\npublic interface IZendiator{");
            foreach (var member in interfaces) text.Append(member.ToFullString());
            text.AppendLine("}\npublic sealed class Zendiator:IZendiator{"); foreach (var member in methods) text.Append(member.ToFullString());
            text.AppendLine("}\ninternal static class ZendiatorGeneratedRegistrar{\ninternal static global::Microsoft.Extensions.DependencyInjection.IServiceCollection Add(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services,global::Zendiator.DependencyInjection.ZendiatorConfigurationSnapshot snapshot)");
            text.Append(registrar.WithStatements(SyntaxFactory.List(statements)).ToFullString()).AppendLine("\n}\n}");
        }
        return text.ToString();
    }
    internal sealed class RouteNames : CSharpSyntaxRewriter
    {
        private readonly Dictionary<string, string> _methods; private readonly Dictionary<string, string> _types;
        internal RouteNames(ClassDeclarationSyntax type, string suffix)
        {
            _methods = type.Members.OfType<MethodDeclarationSyntax>().Where(m => m.Modifiers.Any(SyntaxKind.PrivateKeyword)).ToDictionary(m => m.Identifier.ValueText, m => m.Identifier.ValueText + suffix, StringComparer.Ordinal);
            _types = type.Members.OfType<StructDeclarationSyntax>().ToDictionary(s => s.Identifier.ValueText, s => s.Identifier.ValueText + suffix, StringComparer.Ordinal);
        }
        private static SyntaxToken Rename(SyntaxToken token, string value) => SyntaxFactory.Identifier(token.LeadingTrivia, value, token.TrailingTrivia);
        public override SyntaxNode? VisitMethodDeclaration(MethodDeclarationSyntax node)
        { var result = (MethodDeclarationSyntax)base.VisitMethodDeclaration(node)!; return node.Modifiers.Any(SyntaxKind.PrivateKeyword) && _methods.TryGetValue(node.Identifier.ValueText, out var name) ? result.WithIdentifier(Rename(result.Identifier, name)) : result; }
        public override SyntaxNode? VisitStructDeclaration(StructDeclarationSyntax node)
        { var result = (StructDeclarationSyntax)base.VisitStructDeclaration(node)!; return _types.TryGetValue(node.Identifier.ValueText, out var name) ? result.WithIdentifier(Rename(result.Identifier, name)) : result; }
        public override SyntaxNode? VisitConstructorDeclaration(ConstructorDeclarationSyntax node)
        { var result = (ConstructorDeclarationSyntax)base.VisitConstructorDeclaration(node)!; return _types.TryGetValue(node.Identifier.ValueText, out var name) ? result.WithIdentifier(Rename(result.Identifier, name)) : result; }
        public override SyntaxNode? VisitIdentifierName(IdentifierNameSyntax node)
        {
            if (node.Parent is not (QualifiedNameSyntax or AliasQualifiedNameSyntax or MemberAccessExpressionSyntax) && _types.TryGetValue(node.Identifier.ValueText, out var type)) return node.WithIdentifier(Rename(node.Identifier, type));
            if (node.Parent is InvocationExpressionSyntax call && ReferenceEquals(call.Expression, node) && _methods.TryGetValue(node.Identifier.ValueText, out var method)) return node.WithIdentifier(Rename(node.Identifier, method));
            return base.VisitIdentifierName(node);
        }
        public override SyntaxNode? VisitMemberAccessExpression(MemberAccessExpressionSyntax node)
        {
            var result = (MemberAccessExpressionSyntax)base.VisitMemberAccessExpression(node)!;
            return node.Expression is IdentifierNameSyntax { Identifier.ValueText: "_owner" } && node.Name is IdentifierNameSyntax name && _methods.TryGetValue(name.Identifier.ValueText, out var method) ?
                result.WithName(name.WithIdentifier(Rename(name.Identifier, method))) : result;
        }
    }
}
