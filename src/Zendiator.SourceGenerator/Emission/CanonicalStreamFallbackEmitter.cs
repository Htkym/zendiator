    private static void EmitSynchronousMove(StringBuilder b, string cursor, CanonicalStreamFallbackModel model, CanonicalStreamFallbackSegment segment)
    {
        b.AppendLine("private bool TryPublishCurrent() {");
        var item = model.ItemFlow == null ? "item" : "item0";
        b.AppendLine("var " + item + " = _source!.Current;");
        for (var i = 0; i < segment.Hooks.Count; i++)
        {
            var hook = segment.Hooks[i];
            b.AppendLine("_token.ThrowIfCancellationRequested();");
            b.AppendLine("_hook" + i + " ??= (" + hook.ContractName + ")global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService(services, typeof(" + hook.HookName + "));");
            var call = "_hook" + i + "." + hook.MethodName + "(request, " + item + ", _token)";
            if (hook.Phase == BoundCallbackPhase.Filter) b.AppendLine("if (!" + call + ") return false;");
            else
            {
                var nextItem = model.ItemFlow == null ? item : "item" + (i + 1);
                b.AppendLine((model.ItemFlow == null ? "" : "var ") + nextItem + " = " + call + ";");
                item = nextItem;
            }
        }
        b.AppendLine("_current = " + item + "; _hasCurrent = true; return true; }");
        CanonicalStreamCursorFastPathEmitter.Emit(b, cursor, "_source");
    }
    private static void Acquire(StringBuilder b, BoundAsyncFactoryEmission factory, string receiver)
    {
        var call = "((" + factory.ContractName + ")global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService(services, typeof(" + factory.FactoryName + ")))." + factory.MethodName + "(request, _token)";
        if (factory.AwaitAcquire) call = "(await " + call + ".ConfigureAwait(false))";
        b.AppendLine("                        _token.ThrowIfCancellationRequested();");
        b.AppendLine("                        " + receiver + " = " + call + " ?? throw new global::System.InvalidOperationException(\"The session factory returned null.\");");
    }
