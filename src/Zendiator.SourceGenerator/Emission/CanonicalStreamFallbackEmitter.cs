using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Zendiator.SourceGenerator;

internal static class CanonicalStreamFallbackEmitter
{
    internal static string SourceName(string className) => "StreamSource_" + className.Substring(className.LastIndexOf('_') + 1);

    internal static CanonicalSourceFile Emit(CanonicalStreamFallbackModel model)
    {
        var h = model.Handler;
        if (h.CursorName.Length == 0) throw new InvalidOperationException("A native Stream handler requires its bound cursor type.");
        var source = SourceName(model.ClassName);
        var generic = model.Generic?.TypeParameters ?? "";
        var constraints = model.Generic?.TypeConstraints ?? "";
        var item = model.ItemFlow?.Final.Name ?? h.ItemName;
        var sink = "TSink";
        while (model.Generic?.Parameters.Contains(sink) == true) sink = "_" + sink;
        var b = new StringBuilder();
        b.AppendLine($$"""
            // <auto-generated/>
            #nullable enable
            namespace {{model.Namespace}}
            {
                internal static class {{model.ClassName}}{{generic}}{{constraints}}
                {
                    internal static {{source}}{{generic}} Create(global::System.IServiceProvider services, {{h.RequestName}} request,
                        global::System.Threading.CancellationToken token = default) => new(services, request, token);
                }
                public readonly struct {{source}}{{generic}} : global::System.Collections.Generic.IAsyncEnumerable<{{item}}>{{constraints}}
                {
                    private readonly global::System.IServiceProvider _services;
                    private readonly {{h.RequestName}} _request;
                    private readonly global::System.Threading.CancellationToken _api;
                    internal {{source}}(global::System.IServiceProvider services, {{h.RequestName}} request, global::System.Threading.CancellationToken api)
                    { _services = services; _request = request; _api = api; }
                    private Cursor{{model.ConsumerSegment}} CreateCursor(global::System.Threading.CancellationToken token)
                    {
                        if (_services is null) throw new global::System.InvalidOperationException("The Stream source is uninitialized.");
                        return new Cursor{{model.ConsumerSegment}}(_services, _request, _api, token, null);
                    }
                    public global::System.Collections.Generic.IAsyncEnumerator<{{item}}> GetAsyncEnumerator(
                        global::System.Threading.CancellationToken cancellationToken = default) => CreateCursor(cancellationToken);
                    public global::System.Threading.Tasks.ValueTask ConsumeAsync<{{sink}}>({{sink}} sink,
                        global::System.Threading.CancellationToken cancellationToken = default)
                        where {{sink}} : global::Zendiator.IStreamSink<{{item}}>
                    {
                        if (sink is null) throw new global::System.ArgumentNullException(nameof(sink));
                        return ConsumeCore(CreateCursor(cancellationToken), sink, cancellationToken);
                    }
                    private static async global::System.Threading.Tasks.ValueTask ConsumeCore<{{sink}}>(
                        Cursor{{model.ConsumerSegment}} cursor, {{sink}} sink, global::System.Threading.CancellationToken cancellationToken)
                        where {{sink}} : global::Zendiator.IStreamSink<{{item}}>
                    {
                        try
                        {
                            while (true)
                            {
                                cancellationToken.ThrowIfCancellationRequested();
                                if (!await cursor.MoveNextAsync().ConfigureAwait(false)) return;
                                if (!await sink.OnNextAsync(cursor.Current, cursor.CancellationToken).ConfigureAwait(false)) return;
                            }
                        }
                        finally
                        {
                            await cursor.DisposeAsync().ConfigureAwait(false);
                        }
                    }
            """);
        foreach (var segment in model.Segments) EmitCursor(b, model, segment);
        CanonicalAsyncCallEmitter.EmitCall(b, "OpenHandler", "global::System.Threading.Tasks.ValueTask<" + h.CursorName + ">",
            h.HandlerIsValueType ? "object" : h.HandlerName, h.ContractName, h.MethodName, h.CallTarget,
            new[] { h.RequestName, "global::System.Threading.CancellationToken" }, new[] { "request", "token" }, "", "");
        b.AppendLine("    }");
        b.AppendLine("}");
        return new(model.HintName, b.ToString());
    }

    private static void EmitCursor(StringBuilder b, CanonicalStreamFallbackModel model, CanonicalStreamFallbackSegment segment)
    {
        var h = model.Handler;
        var n = segment.Id;
        var input = segment.SourceItemName ?? h.ItemName;
        var output = segment.OutputItemName ?? h.ItemName;
        var source = segment.Wrapper == null ? h.CursorName : "global::System.Collections.Generic.IAsyncEnumerator<" + input + ">";
        var factory = segment.Wrapper == null ? model.HandlerFactory : segment.WrapperFactory;
        var receiver = segment.Wrapper == null ? Storage(h.HandlerName, h.HandlerIsValueType)
            : Storage(segment.Wrapper.WrapperName, segment.Wrapper.WrapperIsValueType);
        b.AppendLine($$"""
                    private sealed class Cursor{{n}} : global::Zendiator.Streaming.StreamCursorState,
                        global::System.Collections.Generic.IAsyncEnumerator<{{output}}>
                    {
                        private readonly global::System.IServiceProvider _services;
                        private readonly {{h.RequestName}} _request;
                        private readonly global::Zendiator.Streaming.StreamCursorState _root;
                        private {{source}} _source = default!;
                        private bool _acquired;
                        private bool _normalEnd;
                        internal bool CanReopen => _normalEnd && !HasPendingOperation;
                        internal Cursor{{n}}(global::System.IServiceProvider services, {{h.RequestName}} request,
                            global::System.Threading.CancellationToken api, global::System.Threading.CancellationToken enumeration,
                            global::Zendiator.Streaming.StreamCursorState? root) : base(api, enumeration)
                        { _services = services; _request = request; _root = root ?? this; }
            """);
        if (segment.Hooks.Count != 0) b.AppendLine("private " + output + " _current = default!;");
        for (var i = 0; i < segment.Hooks.Count; i++)
            b.AppendLine("private " + Storage(segment.Hooks[i].HookName, segment.Hooks[i].HookIsValueType) + "? _hook" + i + ";");
        if (factory != null) b.AppendLine("private " + receiver + "? _receiver;");
        if (segment.Upstream != null) b.AppendLine("private Upstream" + n + "? _upstream;");
        b.AppendLine($$"""
                        public {{output}} Current
                        {
                            get { ValidateCurrent(); return {{(segment.Hooks.Count == 0 ? "ReadSource(ref _source)" : "_current")}}; }
                        }
                        public global::System.Threading.Tasks.ValueTask<bool> MoveNextAsync()
                        {
                            if (!TryBeginMove()) return new(false);
                            global::System.Threading.Tasks.ValueTask<bool> operation;
                            try
                            {
                                if (!global::System.Object.ReferenceEquals(_root, this) && _root.IsClosed)
                                    operation = MoveFailed(new global::System.ObjectDisposedException("Stream"));
                                else if (TryStart()) operation = StartMoveAsync();
                                else operation = ObserveMove(MoveCoreAsync());
                            }
                            catch (global::System.Exception error) { operation = MoveFailed(error); }
                            return PublishMove(operation);
                        }
                        private async global::System.Threading.Tasks.ValueTask<bool> StartMoveAsync()
                        {
                            try { await InitializeAsync().ConfigureAwait(false); }
                            catch (global::System.Exception error) { return await MoveFailed(error).ConfigureAwait(false); }
                            global::System.Threading.Tasks.ValueTask<bool> pending;
                            try { pending = MoveCoreAsync(); }
                            catch (global::System.Exception error) { return await MoveFailed(error).ConfigureAwait(false); }
                            return await ObserveMove(pending).ConfigureAwait(false);
                        }
                        private global::System.Threading.Tasks.ValueTask<bool> ObserveMove(global::System.Threading.Tasks.ValueTask<bool> pending)
                        {
                            try
                            {
                                if (!pending.IsCompletedSuccessfully) return AwaitMoveAsync(pending);
                                return pending.GetAwaiter().GetResult() ? MoveSucceeded(true) : EndAsync();
                            }
                            catch (global::System.Exception error) { return MoveFailed(error); }
                        }
                        private async global::System.Threading.Tasks.ValueTask<bool> AwaitMoveAsync(global::System.Threading.Tasks.ValueTask<bool> pending)
                        {
                            bool moved;
                            try { moved = await pending.ConfigureAwait(false); }
                            catch (global::System.Exception error) { return await MoveFailed(error).ConfigureAwait(false); }
                            return moved ? await MoveSucceeded(true).ConfigureAwait(false) : await EndAsync().ConfigureAwait(false);
                        }
                        private async global::System.Threading.Tasks.ValueTask<bool> EndAsync()
                        {
                            await MoveSucceeded(false).ConfigureAwait(false);
                            _normalEnd = true;
                            return false;
                        }
                        internal async global::System.Threading.Tasks.ValueTask OpenForMiddlewareAsync()
                        {
                            if (!TryBeginMove()) throw new global::System.ObjectDisposedException("Stream");
                            try
                            {
                                if (_root.IsClosed) throw new global::System.ObjectDisposedException("Stream");
                                if (TryStart()) await InitializeAsync().ConfigureAwait(false);
                            }
                            catch (global::System.Exception error) { await PublishMove(MoveFailed(error)).ConfigureAwait(false); throw; }
                            InitializationSucceeded();
                        }
                        private async global::System.Threading.Tasks.ValueTask InitializeAsync()
                        {
                            _services.GetService(typeof(global::System.IServiceProvider));
            """);
        for (var i = segment.Hooks.Count - 1; i >= 0; i--)
            if (segment.Hooks[i].Factory is { } hookFactory)
                Acquire(b, hookFactory, Storage(segment.Hooks[i].HookName, segment.Hooks[i].HookIsValueType), "_hook" + i);
        if (factory != null) Acquire(b, factory, receiver, "_receiver");
        if (segment.Wrapper is { } wrapper)
        {
            var wrapperValue = factory == null ? Resolve("_services", wrapper.WrapperName, wrapper.ContractName)
                : "(" + wrapper.ContractName + ")_receiver!";
            b.AppendLine("var wrapper = " + wrapperValue + ";");
            b.AppendLine("_upstream = new Upstream" + n + "(_services, this, _root);");
            b.AppendLine("_source = await wrapper." + wrapper.MethodName + "(_request, _upstream, Token).ConfigureAwait(false)");
            b.AppendLine("""    ?? throw new global::System.InvalidOperationException("A Stream middleware returned a null cursor.");""");
        }
        else
        {
            var value = factory == null ? Resolve("_services", h.HandlerName, h.HandlerIsValueType ? "object" : h.HandlerName)
                : h.HandlerIsValueType ? "(object)_receiver!" : "(" + h.HandlerName + ")_receiver!";
            b.AppendLine("_source = await OpenHandler(" + value + ", _request, Token).ConfigureAwait(false);");
            if (!h.CursorIsValueType) b.AppendLine("""if (_source is null) throw new global::System.InvalidOperationException("A Stream handler returned a null cursor.");""");
        }
        b.AppendLine("_acquired = true;");
        b.AppendLine("}");
        var cursorType = "TSourceCursor";
        while (model.Generic?.Parameters.Contains(cursorType) == true) cursorType = "_" + cursorType;
        b.AppendLine("private static global::System.Threading.Tasks.ValueTask<bool> MoveSource<" + cursorType + ">(ref " + cursorType + " source) where " + cursorType + " : global::System.Collections.Generic.IAsyncEnumerator<" + input + "> => source.MoveNextAsync();");
        b.AppendLine("private static " + input + " ReadSource<" + cursorType + ">(ref " + cursorType + " source) where " + cursorType + " : global::System.Collections.Generic.IAsyncEnumerator<" + input + "> => source.Current;");
        b.AppendLine("private static global::System.Threading.Tasks.ValueTask DisposeSource<" + cursorType + ">(ref " + cursorType + " source) where " + cursorType + " : global::System.Collections.Generic.IAsyncEnumerator<" + input + "> => source.DisposeAsync();");
        EmitMove(b, segment);
        EmitCleanup(b, segment, factory);
        b.AppendLine("}");
        if (segment.Upstream is { } upstream) EmitUpstream(b, h, segment, upstream);
    }

    private static void EmitMove(StringBuilder b, CanonicalStreamFallbackSegment segment)
    {
        var asynchronous = segment.Hooks.Any(h => h.Completion == BoundCompletionKind.ValueTask);
        b.AppendLine("private global::System.Threading.Tasks.ValueTask<bool> MoveCoreAsync() {");
        if (segment.Hooks.Count == 0)
        {
            b.AppendLine("Token.ThrowIfCancellationRequested(); return MoveSource(ref _source); }");
            return;
        }
        b.AppendLine("while (true) { Token.ThrowIfCancellationRequested(); var pending = MoveSource(ref _source);");
        b.AppendLine("if (!pending.IsCompletedSuccessfully) return AwaitSourceAsync(pending);");
        b.AppendLine("if (!pending.GetAwaiter().GetResult()) return new(false);");
        if (asynchronous)
        {
            b.AppendLine("var publication = PublishAsync(); if (!publication.IsCompletedSuccessfully) return AwaitPublicationAsync(publication);");
            b.AppendLine("if (publication.GetAwaiter().GetResult()) return new(true);");
        }
        else b.AppendLine("if (TryPublish()) return new(true);");
        b.AppendLine("} }");
        b.AppendLine("private async global::System.Threading.Tasks.ValueTask<bool> AwaitSourceAsync(global::System.Threading.Tasks.ValueTask<bool> pending) {");
        b.AppendLine("var moved = await pending.ConfigureAwait(false); while (moved) {");
        b.AppendLine(asynchronous ? "if (await PublishAsync().ConfigureAwait(false)) return true;" : "if (TryPublish()) return true;");
        b.AppendLine("Token.ThrowIfCancellationRequested(); moved = await MoveSource(ref _source).ConfigureAwait(false); } return false; }");
        if (asynchronous)
        {
            b.AppendLine("private async global::System.Threading.Tasks.ValueTask<bool> AwaitPublicationAsync(global::System.Threading.Tasks.ValueTask<bool> pending) {");
            b.AppendLine("if (await pending.ConfigureAwait(false)) return true; while (true) { Token.ThrowIfCancellationRequested();");
            b.AppendLine("if (!await MoveSource(ref _source).ConfigureAwait(false)) return false; if (await PublishAsync().ConfigureAwait(false)) return true; } }");
        }
        b.AppendLine(asynchronous ? "private async global::System.Threading.Tasks.ValueTask<bool> PublishAsync() {" : "private bool TryPublish() {");
        b.AppendLine("var item0 = ReadSource(ref _source);");
        var item = "item0";
        for (var i = 0; i < segment.Hooks.Count; i++)
        {
            var hook = segment.Hooks[i];
            b.AppendLine("Token.ThrowIfCancellationRequested();");
            if (hook.Factory == null) b.AppendLine("_hook" + i + " ??= " + Resolve("_services", hook.HookName, Storage(hook.HookName, hook.HookIsValueType)) + ";");
            var call = "((" + hook.ContractName + ")_hook" + i + "!)." + hook.MethodName + "(_request, " + item + ", Token)";
            if (hook.Completion == BoundCompletionKind.ValueTask) call = "(await " + call + ".ConfigureAwait(false))";
            if (hook.Phase == BoundCallbackPhase.Filter) b.AppendLine("if (!" + call + ") return false;");
            else if (hook.Phase == BoundCallbackPhase.Map)
            { var next = "item" + (i + 1); b.AppendLine("var " + next + " = " + call + ";"); item = next; }
            else throw new InvalidOperationException("An item region contains a non-item callback.");
        }
        b.AppendLine("_current = " + item + "; return true; }");
    }

    private static void EmitCleanup(StringBuilder b, CanonicalStreamFallbackSegment segment, BoundAsyncFactoryEmission? receiverFactory)
    {
        b.AppendLine("protected override async global::System.Threading.Tasks.ValueTask DisposeCoreAsync() {");
        b.AppendLine("try { if (_acquired) { _acquired = false; var source = _source; _source = default!; await DisposeSource(ref source).ConfigureAwait(false); } }");
        b.AppendLine("finally {");
        var depth = 1;
        if (segment.Upstream != null)
        { b.AppendLine("try { var upstream = _upstream; _upstream = null; if (upstream is not null) await upstream.DisposeActiveAsync().ConfigureAwait(false); } finally {"); depth++; }
        void Cleanup(BoundAsyncFactoryEmission? factory, string field)
        {
            if (factory?.CleanupContractName is not { } contract) return;
            b.AppendLine("try { var session = " + field + "; " + field + " = null; if (session is not null) await ((" + contract + ")session).DisposeAsync().ConfigureAwait(false); } finally {");
            depth++;
        }
        Cleanup(receiverFactory, "_receiver");
        for (var i = 0; i < segment.Hooks.Count; i++) Cleanup(segment.Hooks[i].Factory, "_hook" + i);
        for (var i = 0; i < depth; i++) b.AppendLine("}");
        b.AppendLine("}");
    }

    private static void EmitUpstream(StringBuilder b, BoundStreamHandlerEmission handler, CanonicalStreamFallbackSegment segment, int upstream)
    {
        var n = segment.Id;
        var item = segment.SourceItemName ?? handler.ItemName;
        b.AppendLine($$"""
                    private sealed class Upstream{{n}}(global::System.IServiceProvider services,
                        global::Zendiator.Streaming.StreamCursorState owner, global::Zendiator.Streaming.StreamCursorState root)
                        : global::Zendiator.IStreamUpstream<{{handler.RequestName}}, {{item}}>
                    {
                        private Cursor{{upstream}}? _active;
                        private int _opening;
                        public global::System.Threading.Tasks.ValueTask<global::System.Collections.Generic.IAsyncEnumerator<{{item}}>> OpenAsync(
                            {{handler.RequestName}} request, global::System.Threading.CancellationToken token)
                        {
                            if (global::System.Threading.Interlocked.CompareExchange(ref _opening, 1, 0) != 0)
                                throw new global::System.InvalidOperationException("Await the preceding Stream open.");
                            try
                            {
                                if (owner.IsClosed || root.IsClosed) throw new global::System.ObjectDisposedException("Stream");
                                if (_active is { CanReopen: false }) throw new global::System.InvalidOperationException("The preceding Stream cursor must reach normal EOF and finish cleanup before reopening.");
                                {{(handler.RequestIsValueType ? "" : "global::System.ArgumentNullException.ThrowIfNull(request);")}}
                                var cursor = new Cursor{{upstream}}(services, request, token, default, root);
                                _active = cursor;
                                return OpenCursorAsync(cursor);
                            }
                            catch { global::System.Threading.Volatile.Write(ref _opening, 0); throw; }
                        }
                        private async global::System.Threading.Tasks.ValueTask<global::System.Collections.Generic.IAsyncEnumerator<{{item}}>> OpenCursorAsync(Cursor{{upstream}} cursor)
                        {
                            try { await cursor.OpenForMiddlewareAsync().ConfigureAwait(false); return cursor; }
                            finally { global::System.Threading.Volatile.Write(ref _opening, 0); }
                        }
                        internal async global::System.Threading.Tasks.ValueTask DisposeActiveAsync()
                        {
                            var active = _active; _active = null;
                            if (active is not null) await active.DisposeAsync().ConfigureAwait(false);
                        }
                    }
            """);
    }

    private static string Storage(string type, bool valueType) => valueType ? "object" : type;
    private static string Resolve(string services, string type, string result) => "(" + result + ")global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService(" + services + ", typeof(" + type + "))";
    private static void Acquire(StringBuilder b, BoundAsyncFactoryEmission factory, string contract, string field)
    {
        b.AppendLine("Token.ThrowIfCancellationRequested();");
        var call = "(" + Resolve("_services", factory.FactoryName, factory.ContractName) + ")." + factory.MethodName + "(_request, Token)";
        if (factory.AwaitAcquire) call = "(await " + call + ".ConfigureAwait(false))";
        b.AppendLine(field + " = (" + contract + ")" + call + """ ?? throw new global::System.InvalidOperationException("The session factory returned null.");""");
    }
}
